/**
 * Vendored icon geometry for the default element catalog (`cp3-002`).
 *
 * WHAT IS IN HERE, AND WHY IT IS DATA RATHER THAN A DEPENDENCY.
 *
 * 307 icons transcribed from two upstream sets. Nothing is imported at runtime:
 * an icon package would put its whole index in the dependency graph for the
 * ~15% of it a catalog uses, and this package must not grow a dependency to
 * ship artwork. The geometry is copied, the provenance is recorded per entry
 * (`license` + `upstreamUrl`), and the upstream copyright notices are
 * reproduced in `DEFAULT_ELEMENT_ATTRIBUTIONS` and in
 * `docs/element-catalog-attribution.md`, which ships in the published package
 * (`package.json` `files` lists `docs`).
 *
 * LICENCE PROVENANCE — TRANSCRIBED, NOT REMEMBERED.
 *
 * Both sets are **MIT**, read from the LICENSE file published in each set's own
 * npm tarball on 2026-08-07, not from reputation:
 *
 * - `bootstrap-icons@1.13.1/LICENSE` — "The MIT License (MIT) / Copyright (c)
 *   2019-2024 The Bootstrap Authors". `package.json` `license: "MIT"`.
 * - `heroicons@2.2.0/LICENSE` — "MIT License / Copyright (c) Tailwind Labs,
 *   Inc.". `package.json` `license: "MIT"`.
 *
 * MIT requires the notice to travel with the copy. It does, twice: as data a
 * host can render ({@link BOOTSTRAP_ATTRIBUTION} /
 * {@link HEROICONS_ATTRIBUTION}, which ship in `dist`) and as a document in the
 * published tarball. `cp6-006`'s audit is a pure read of the former.
 *
 * Lucide was NOT used. It is ISC, which is not in this catalog's allowed set
 * (`OFL-1.1` / `MIT` / `Apache-2.0` / `CC0-1.0`), and it is the icon set this
 * workspace already has installed — so the omission is deliberate and is
 * recorded here rather than left to look like an oversight.
 *
 * THE SELECTION RULE, WHICH IS A RENDERING CONSTRAINT AND NOT AN AESTHETIC ONE.
 *
 * `CanvasPathNode` has no `fill-rule` field, and neither renderer emits one:
 * the SVG serializer writes a bare `<path d>` (`core/serialize/svg.ts:1022`)
 * and Konva's `Path` fills non-zero. So an icon whose upstream markup asks for
 * `fill-rule="evenodd"` would render as a solid blob wherever it relies on a
 * hole. Every filled icon here is therefore a **single `<path>` carrying no
 * `fill-rule` and no `clip-rule`** — 960 of Bootstrap's 2,078 qualify, and the
 * 151 used are drawn from those. The rest were left out rather than transcribed
 * and hoped for.
 *
 * The outline set has no such exposure: stroking has no winding rule at all.
 * Heroicons' 24px outline icons are `fill="none" stroke="currentColor"
 * stroke-width="1.5"` with `stroke-linejoin="round"` on every one of their 337
 * paths (checked across all 324 icons, not sampled), so a multi-path icon's
 * `d` values concatenate into one path with **identical** rendering — which is
 * what makes every outline entry a single node with a single stroke to change.
 *
 * WHAT A ROW IS.
 *
 * Just data: this module holds no `CanvasElementEntry`. The factories in
 * `catalog-builders.ts` turn a row into one, so the sizing model and the
 * `recolor` contract have one implementation rather than 307.
 */

import type { CanvasBounds } from "@anvilkit/canvas-core";

/** One vendored icon: identity, search vocabulary, and its path data. */
export interface CatalogIconRow {
	/** Catalog-unique entry id. */
	readonly id: string;
	/** Display name, including its `(solid)`/`(outline)` style suffix. */
	readonly name: string;
	/** The upstream file's own name, e.g. `house-door-fill`. Provenance, and searched. */
	readonly source: string;
	readonly tags: readonly string[];
	readonly keywords: readonly string[];
	/** SVG path data, verbatim from upstream, in that set's viewBox. */
	readonly d: string;
}

/**
 * An upstream set's licensing record. Exported as DATA because a notice a host
 * cannot render is not a notice — `cp3-003` can surface it, and `cp6-006`'s
 * audit reads it instead of re-deriving it from a document.
 */
export interface CatalogAttribution {
	/** Human-readable name of the upstream set, or of this package's own work. */
	readonly setName: string;
	/** SPDX identifier, transcribed from the set's own LICENSE file. */
	readonly license: string;
	/** The copyright line the licence requires be preserved. */
	readonly copyright: string;
	/** Where the licence text and the geometry both come from. */
	readonly upstreamUrl: string;
	/** The exact artifact the geometry and the licence were read from. */
	readonly verifiedFrom: string;
}

