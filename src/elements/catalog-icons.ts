/**
 * Per-entry provenance URL for a Bootstrap icon. The specimen page, not the raw
 * file: it is what a person checking an attribution actually wants.
 */
export function bootstrapUpstreamUrl(source: string): string {
	return `https://icons.getbootstrap.com/icons/${source}/`;
}

